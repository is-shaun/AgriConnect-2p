"""Generate the clearly labelled SYNTHETIC demo price dataset.

These numbers are invented by a stochastic process (trend + seasonality + persistent
shocks + noise). They exist only so the application and ML pipeline can be developed
and demonstrated end-to-end. They are NOT real market prices and must never be shown
or used as such. Every record carries the source label below.

Usage:
    python ml/generate_demo_data.py                       # writes ml/data/demo_market_prices.csv
    python ml/generate_demo_data.py --end 2026-10-16 --out path.csv
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

DEMO_SOURCE = "DEMO – synthetic data generated by AgriConnect (not real market prices)"
GENERATOR_VERSION = "demo-gen-1"

# name: (category, base Rs/quintal, seasonal amplitude, weekly shock sigma, seasonal peak day-of-year)
CROPS = {
    "Wheat": ("Cereals", 2450, 0.06, 0.012, 300),
    "Paddy (Common)": ("Cereals", 2250, 0.05, 0.012, 240),
    "Maize": ("Cereals", 2100, 0.07, 0.018, 200),
    "Onion": ("Vegetables", 1900, 0.30, 0.060, 290),
    "Tomato": ("Vegetables", 1600, 0.35, 0.080, 190),
    "Potato": ("Vegetables", 1250, 0.18, 0.035, 330),
    "Mustard": ("Oilseeds", 5650, 0.06, 0.015, 20),
    "Bengal Gram (Chana)": ("Pulses", 5800, 0.05, 0.015, 40),
}

# (state, district, market, price multiplier, crops traded)
MARKETS = [
    ("Bihar", "Patna", "Patna", 1.00, ["Wheat", "Paddy (Common)", "Maize", "Onion", "Potato", "Tomato"]),
    ("Uttar Pradesh", "Lucknow", "Lucknow", 1.02, ["Wheat", "Paddy (Common)", "Potato", "Onion", "Tomato", "Mustard"]),
    ("Maharashtra", "Nashik", "Lasalgaon", 0.97, ["Onion", "Tomato", "Maize", "Bengal Gram (Chana)"]),
    ("Madhya Pradesh", "Indore", "Indore", 0.99, ["Wheat", "Maize", "Bengal Gram (Chana)", "Mustard", "Onion"]),
    ("Punjab", "Ludhiana", "Khanna", 1.03, ["Wheat", "Paddy (Common)", "Maize", "Potato"]),
    ("Odisha", "Khordha", "Bhubaneswar", 1.05, ["Paddy (Common)", "Potato", "Onion", "Tomato"]),
    ("Rajasthan", "Jaipur", "Jaipur (Grain)", 1.01, ["Mustard", "Bengal Gram (Chana)", "Wheat"]),
]


def generate(start="2023-10-02", end="2026-10-16", seed=42) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    days = pd.date_range(start, end, freq="D")
    rows = []
    for state, district, market, mult, crops in MARKETS:
        for crop in crops:
            category, base, amp, sigma, peak = CROPS[crop]
            local = base * mult * rng.uniform(0.96, 1.04)
            trend = rng.normal(0.04, 0.02)  # yearly log drift (~4% inflation)
            shock = 0.0
            for i, d in enumerate(days):
                # persistent AR(1) shock evolving daily (~0.97 weekly persistence)
                shock = 0.996 * shock + rng.normal(0, sigma / np.sqrt(7))
                if d.weekday() == 6 or rng.random() < 0.12:  # Sundays closed, ~12% no arrivals
                    continue
                season = amp * np.cos(2 * np.pi * (d.dayofyear - peak) / 365.25)
                logp = np.log(local) + trend * i / 365.25 + season + shock + rng.normal(0, sigma / 3)
                modal = float(np.exp(logp))
                spread_lo, spread_hi = rng.uniform(0.03, 0.10), rng.uniform(0.03, 0.10)
                rows.append({
                    "state": state, "district": district, "market": market, "commodity": crop,
                    "category": category, "unit": "Rs/quintal",
                    "arrival_date": d.date().isoformat(),
                    "min_price": round(modal * (1 - spread_lo)),
                    "max_price": round(modal * (1 + spread_hi)),
                    "modal_price": round(modal),
                    "source": DEMO_SOURCE,
                })
    return pd.DataFrame(rows)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--start", default="2023-10-02")
    ap.add_argument("--end", default="2026-10-16")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", default=str(Path(__file__).parent / "data" / "demo_market_prices.csv"))
    args = ap.parse_args()
    df = generate(args.start, args.end, args.seed)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(args.out, index=False)
    print(f"Wrote {len(df):,} SYNTHETIC demo rows ({df.groupby(['commodity','market']).ngroups} series) to {args.out}")


if __name__ == "__main__":
    main()
